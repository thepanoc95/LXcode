std::string shellQuote(const std::string& value) {
    std::string quoted = "'";
    for (const char character : value) {
        if (character == '\'') quoted += "'\\''";
        else quoted += character;
    }
    quoted += '\'';
    return quoted;
}

// Escapes a literal path for use inside a double-quoted shell expansion.
std::string shellDoubleQuoteInner(const std::string& value) {
    std::string escaped;
    for (const char character : value) {
        if (character == '\\' || character == '"' || character == '$' || character == '`')
            escaped += '\\';
        escaped += character;
    }
    return escaped;
}

std::string substitute(std::string text,
                       const std::vector<std::pair<std::string, std::string>>& replacements) {
    for (const auto& [key, value] : replacements) {
        const auto placeholder = "@" + key + "@";
        std::size_t position = text.find(placeholder);
        while (position != std::string::npos) {
            text.replace(position, placeholder.size(), value);
            position = text.find(placeholder, position + value.size());
        }
    }
    return text;
}

Expected<void> writeFile(const std::filesystem::path& path, const std::string& contents) {
    return fs::writeTextAtomic(path, contents, false);
}

Expected<void> writeScript(const std::filesystem::path& path, const std::string& contents) {
    auto saved = writeFile(path, contents);
    if (!saved) return saved;
    std::error_code ec;
    std::filesystem::permissions(path,
                                 std::filesystem::perms::owner_exec |
                                     std::filesystem::perms::group_exec |
                                     std::filesystem::perms::others_exec,
                                 std::filesystem::perm_options::add, ec);
    if (ec) return Expected<void>::failure("cannot make " + path.string() + " executable: " +
                                           ec.message());
    return {};
}

plist::Value stringArray(const std::vector<std::string>& values) {
    auto array = plist::Value::arr();
    for (const auto& value : values) array.array.push_back(plist::Value::string(value));
    return array;
}

std::filesystem::path sdkPath(const std::filesystem::path& root) {
    return root / platformName / "Developer" / "SDKs" / sdkName;
}

std::filesystem::path toolchainBin(const std::filesystem::path& root) {
    return root / toolchainName / "usr" / "bin";
}

std::filesystem::path resolvedSysroot(const std::filesystem::path& root, const Manifest& manifest) {
    if (manifest.sysroot.empty()) return root / "sysroot";
    return manifest.sysroot.is_absolute() ? manifest.sysroot : root / manifest.sysroot;
}

std::string compilerWrapper(const std::string& architecture, bool cxx, const Manifest& manifest) {
    const auto target = llvmTarget(architecture);
    const auto configured = cxx ? manifest.clangxx : manifest.clang;
    const std::string variable = cxx ? "LXCODE_LINUX_CLANGXX" : "LXCODE_LINUX_CLANG";
    const std::string defaultTool = cxx ? "clang++" : "clang";

    std::string sysrootExpression;
    if (manifest.sysroot.empty()) {
        sysrootExpression = "${BUNDLE_DIR}/sysroot";
    } else if (manifest.sysroot.is_absolute()) {
        sysrootExpression = shellDoubleQuoteInner(manifest.sysroot.string());
    } else {
        sysrootExpression = "${BUNDLE_DIR}/" + shellDoubleQuoteInner(manifest.sysroot.string());
    }

    // Xcode passes Darwin-specific -arch flags. They are removed here because
    // clang rejects them for Linux targets; the .xcconfig selects the wrapper
    // for the requested LINUX_ARCH instead.
    const std::string script = R"SH(#!/bin/sh
# Generated by LXcode for an Xcode Linux SDK bundle. Do not edit.
set -eu
BUNDLE_DIR="$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)"
SYSROOT="${LXCODE_LINUX_SYSROOT:-@SYSROOT@}"
COMPILER=@COMPILER@
if [ -z "$COMPILER" ]; then COMPILER="${@VARIABLE@:-}"; fi
if [ -z "$COMPILER" ]; then COMPILER="$(command -v @TOOL@ || true)"; fi
if [ -z "$COMPILER" ]; then
  echo "lxcode: no @TOOL@ found; install LLVM or set @VARIABLE@" >&2
  exit 127
fi
ARGS=''
COMPILE_ONLY=no
while [ "$#" -gt 0 ]; do
  case "$1" in
    -c) COMPILE_ONLY=yes ;;
    -arch) shift; if [ "$#" -gt 0 ]; then shift; fi; continue ;;
    -arch=*) shift; continue ;;
  esac
  QUOTED=$(printf '%s' "$1" | sed "s/'/'\\\\''/g")
  ARGS="$ARGS '$QUOTED'"
  shift
done
eval "set -- $ARGS"
if [ "$COMPILE_ONLY" = yes ]; then
  exec "$COMPILER" --target=@TARGET@ --sysroot="$SYSROOT" "$@"
fi
exec "$COMPILER" --target=@TARGET@ --sysroot="$SYSROOT" -fuse-ld=lld "$@"
)SH";
    return substitute(script, {{"SYSROOT", sysrootExpression},
                               {"COMPILER", shellQuote(configured)},
                               {"VARIABLE", variable},
                               {"TOOL", defaultTool},
                               {"TARGET", shellQuote(target)}});
}

std::string llvmToolWrapper(const std::string& role, const std::string& binary,
                            const Manifest& manifest) {
    std::string script = "#!/bin/sh\n";
    script += "# Generated by LXcode for an Xcode Linux SDK bundle. Do not edit.\n";
    script += "set -eu\n";
    script += "LLVM_BIN=" + shellQuote(manifest.llvmBin.string()) + "\n";
    script += "if [ -z \"$LLVM_BIN\" ]; then LLVM_BIN=\"${LXCODE_LINUX_LLVM_BIN:-}\"; fi\n";
    script += "if [ -n \"$LLVM_BIN\" ] && [ -x \"$LLVM_BIN/" + binary + "\" ]; then\n";
    script += "  exec \"$LLVM_BIN/" + binary + "\" \"$@\"\n";
    script += "fi\n";
    script += "if command -v " + binary + " >/dev/null 2>&1; then\n";
    script += "  exec " + binary + " \"$@\"\n";
    script += "fi\n";
    script += "echo 'lxcode: " + binary +
              " not found; install LLVM tools or set LXCODE_LINUX_LLVM_BIN' >&2\n";
    script += "exit 127\n";
    (void)role;
    return script;
}

bool isExecutable(const std::filesystem::path& path) {
    std::error_code ec;
    const auto status = std::filesystem::status(path, ec);
    if (ec || !std::filesystem::is_regular_file(status)) return false;
    const auto permissions = status.permissions();
    return (permissions & std::filesystem::perms::owner_exec) != std::filesystem::perms::none;
}

std::string targetText(const plist::Value* value) {
    return value ? value->text : std::string();
}

