std::string llvmTarget(const std::string& architecture) {
    if (architecture == "x86_64" || architecture == "amd64") return "x86_64-unknown-linux-gnu";
    if (architecture == "arm64" || architecture == "aarch64") return "aarch64-unknown-linux-gnu";
    return {};
}

std::string sdkSettingsPlist(const Manifest& manifest) {
    plist::Document document;
    auto settings = plist::Value::dict();

    settings.set("CanonicalName", plist::Value::string("linux"));
    settings.set("DisplayName", plist::Value::string(manifest.name + " " + manifest.versionString));
    settings.set("MinimalDisplayName", plist::Value::string(manifest.name));
    settings.set("Version", plist::Value::string(manifest.versionString));
    settings.set("isBaseSDK", plist::Value::string("YES"));
    settings.set("MinimumSupportedToolsVersion", plist::Value::string("13.0"));

    auto toolchains = plist::Value::arr();
    toolchains.array.push_back(plist::Value::string(manifest.identifier));
    settings.set("Toolchains", toolchains);
    settings.set("SupportedArchs", stringArray(manifest.architectures));

    auto targets = plist::Value::dict();
    auto linuxTarget = plist::Value::dict();
    linuxTarget.set("Archs", stringArray(manifest.architectures));
    targets.set("linux", linuxTarget);
    settings.set("SupportedTargets", targets);

    auto defaults = plist::Value::dict();
    defaults.set("PLATFORM_NAME", plist::Value::string("linux"));
    defaults.set("SUPPORTED_PLATFORMS", plist::Value::string("linux"));
    settings.set("DefaultProperties", defaults);

    auto custom = plist::Value::dict();
    custom.set("LINUX_SDK_BUNDLE", plist::Value::string("$(SDK_DIR)/../../../.."));
    custom.set("LINUX_TOOLCHAIN_BIN",
               plist::Value::string("$(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin"));
    settings.set("CustomProperties", custom);

    document.root() = settings;
    return document.serialize();
}

std::string platformInfoPlist(const Manifest& manifest) {
    plist::Document document;
    auto info = plist::Value::dict();
    info.set("CFBundleIdentifier", plist::Value::string(manifest.identifier + ".platform"));
    info.set("CFBundleName", plist::Value::string("Linux"));
    info.set("CFBundleDisplayName", plist::Value::string(manifest.name));
    info.set("CFBundleVersion", plist::Value::string(manifest.versionString));
    document.root() = info;
    return document.serialize();
}

std::string toolchainInfoPlist(const Manifest& manifest) {
    plist::Document document;
    auto info = plist::Value::dict();
    info.set("Identifier", plist::Value::string(manifest.identifier));
    info.set("CompatibilityVersion", plist::Value::string("2"));
    info.set("DisplayName", plist::Value::string(manifest.name + " toolchain"));
    info.set("Version", plist::Value::string(manifest.versionString));
    info.set("Alias", plist::Value::string("Linux"));
    document.root() = info;
    return document.serialize();
}

std::string xcconfigContents(const std::filesystem::path& bundleRoot) {
    const auto absolute = std::filesystem::absolute(bundleRoot).lexically_normal().string();
    std::string text = "// Generated by LXcode for an Xcode Linux SDK bundle.\n";
    text += "// Include this file in your target's configuration, then set LINUX_ARCH.\n";
    text += "// Override LINUX_SDK_BUNDLE here to relocate the bundle.\n";
    text += "LINUX_SDK_BUNDLE = " + absolute + "\n";
    text += "LINUX_ARCH = x86_64\n";
    text += "ARCHS = $(LINUX_ARCH)\n";
    text += "SDKROOT = $(LINUX_SDK_BUNDLE)/Linux.platform/Developer/SDKs/Linux.sdk\n";
    text += "SUPPORTED_PLATFORMS = linux\n";
    text += "CC = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/$(LINUX_ARCH)-unknown-linux-gnu-clang\n";
    text += "CXX = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/$(LINUX_ARCH)-unknown-linux-gnu-clang++\n";
    text += "LD = $(CXX)\n";
    text += "AR = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/ar\n";
    text += "NM = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/nm\n";
    text += "RANLIB = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/ranlib\n";
    text += "STRIP = $(LINUX_SDK_BUNDLE)/Linux.xctoolchain/usr/bin/strip\n";
    text += "OTHER_LDFLAGS = $(inherited) -fuse-ld=lld\n";
    text += "CODE_SIGNING_ALLOWED = NO\n";
    text += "CODE_SIGN_IDENTITY = \n";
    text += "SKIP_INSTALL = YES\n";
    return text;
}

std::string installScriptContents() {
    std::string script = "#!/bin/sh\n";
    script += "# Generated by LXcode. Installs the bundle into an Xcode developer directory.\n";
    script += "set -eu\n";
    script += "BUNDLE_DIR=\"$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\"\n";
    script += "DEVELOPER_DIR=\"${1:-}\"\n";
    script += "if [ -z \"$DEVELOPER_DIR\" ]; then\n";
    script += "  DEVELOPER_DIR=\"$(xcode-select -p 2>/dev/null || true)\"\n";
    script += "fi\n";
    script += "if [ ! -d \"$DEVELOPER_DIR\" ]; then\n";
    script += "  echo 'usage: install.sh /Applications/Xcode.app/Contents/Developer' >&2\n";
    script += "  exit 2\n";
    script += "fi\n";
    script += "mkdir -p \"$DEVELOPER_DIR/Platforms\" \"$DEVELOPER_DIR/Toolchains\"\n";
    script += "rm -rf \"$DEVELOPER_DIR/Platforms/Linux.platform\"\n";
    script += "rm -rf \"$DEVELOPER_DIR/Toolchains/Linux.xctoolchain\"\n";
    script += "cp -R \"$BUNDLE_DIR/Linux.platform\" \"$DEVELOPER_DIR/Platforms/\"\n";
    script += "cp -R \"$BUNDLE_DIR/Linux.xctoolchain\" \"$DEVELOPER_DIR/Toolchains/\"\n";
    script += "echo \"Installed into $DEVELOPER_DIR. Restart Xcode and choose the Linux toolchain.\"\n";
    return script;
}

