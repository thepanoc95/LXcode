Expected<Manifest> readManifest(const std::filesystem::path& root) {
    auto text = fs::readText(root / manifestFileName);
    if (!text) return Expected<Manifest>::failure("cannot read manifest: " + text.error());
    try {
        const auto json = nlohmann::json::parse(*text);
        if (json.value("format", std::string("lxcode-xcode-linux-sdk")) !=
            "lxcode-xcode-linux-sdk")
            return Expected<Manifest>::failure("not an LXcode Linux SDK bundle manifest");
        Manifest manifest;
        manifest.version = json.value("version", 1);
        if (manifest.version != 1)
            return Expected<Manifest>::failure("unsupported bundle version: " +
                                               std::to_string(manifest.version));
        manifest.name = json.value("name", "Linux");
        manifest.identifier = json.value("identifier", "dev.lxcode.sdk.linux");
        manifest.versionString = json.value("versionString", "1.0");
        manifest.sysroot = json.value("sysroot", "");
        manifest.clang = json.value("clang", "");
        manifest.clangxx = json.value("clangxx", "");
        manifest.llvmBin = json.value("llvmBin", "");
        if (json.contains("architectures") && json["architectures"].is_array())
            manifest.architectures = json["architectures"].get<std::vector<std::string>>();
        return manifest;
    } catch (const std::exception& error) {
        return Expected<Manifest>::failure(std::string("invalid manifest: ") + error.what());
    }
}

Expected<void> writeManifest(const std::filesystem::path& root, const Manifest& manifest) {
    nlohmann::json json;
    json["format"] = "lxcode-xcode-linux-sdk";
    json["version"] = 1;
    json["name"] = manifest.name;
    json["identifier"] = manifest.identifier;
    json["versionString"] = manifest.versionString;
    json["architectures"] = manifest.architectures;
    json["sysroot"] = manifest.sysroot.string();
    json["clang"] = manifest.clang;
    json["clangxx"] = manifest.clangxx;
    json["llvmBin"] = manifest.llvmBin.string();
    return writeFile(root / manifestFileName, json.dump(2) + "\n");
}

Expected<void> writeWrappers(const std::filesystem::path& root, const Manifest& manifest) {
    const auto bin = toolchainBin(root);
    std::error_code ec;
    std::filesystem::create_directories(bin, ec);
    if (ec) return Expected<void>::failure("cannot create toolchain bin directory: " + ec.message());

    // Remove previously generated wrappers so architecture changes do not
    // leave stale compilers behind. Only known generated names are touched.
    for (std::filesystem::directory_iterator it(bin, ec), end; it != end; it.increment(ec)) {
        if (ec) break;
        const auto name = it->path().filename().string();
        const bool generated =
            (strings::endsWith(name, "-unknown-linux-gnu-clang") ||
             strings::endsWith(name, "-unknown-linux-gnu-clang++") ||
             name == "clang" || name == "clang++" || name == "ar" || name == "nm" ||
             name == "ranlib" || name == "ld" || name == "strip");
        if (generated) std::filesystem::remove(it->path(), ec);
    }

    const auto architectures = manifest.architectures.empty()
                                   ? std::vector<std::string>{"x86_64"}
                                   : manifest.architectures;
    for (const auto& architecture : architectures) {
        if (llvmTarget(architecture).empty())
            return Expected<void>::failure("unsupported architecture: " + architecture);
        auto saved = writeScript(bin / (architecture + "-unknown-linux-gnu-clang"),
                                 compilerWrapper(architecture, false, manifest));
        if (!saved) return saved;
        saved = writeScript(bin / (architecture + "-unknown-linux-gnu-clang++"),
                            compilerWrapper(architecture, true, manifest));
        if (!saved) return saved;
    }
    const auto first = architectures.front();
    auto saved = writeScript(bin / "clang", compilerWrapper(first, false, manifest));
    if (!saved) return saved;
    saved = writeScript(bin / "clang++", compilerWrapper(first, true, manifest));
    if (!saved) return saved;

    struct Tool {
        const char* name;
        const char* binary;
    };
    const Tool tools[] = {{"ar", "llvm-ar"},       {"nm", "llvm-nm"},
                          {"ranlib", "llvm-ranlib"}, {"ld", "ld.lld"},
                          {"strip", "llvm-strip"}};
    for (const auto& tool : tools) {
        saved = writeScript(bin / tool.name, llvmToolWrapper(tool.name, tool.binary, manifest));
        if (!saved) return saved;
    }
    return {};
}

Expected<std::filesystem::path> createBundle(const std::filesystem::path& root,
                                             const Manifest& manifest) {
    if (manifest.identifier.empty())
        return Expected<std::filesystem::path>::failure("bundle identifier cannot be empty");
    if (manifest.architectures.empty())
        return Expected<std::filesystem::path>::failure("at least one architecture is required");
    for (const auto& architecture : manifest.architectures)
        if (llvmTarget(architecture).empty())
            return Expected<std::filesystem::path>::failure("unsupported architecture: " +
                                                            architecture);

    std::error_code ec;
    const auto sdk = sdkPath(root);
    const auto toolchain = toolchainBin(root);
    // The bundle keeps its own empty sysroot placeholder. A user-supplied
    // sysroot is only referenced; it is never created or modified here.
    const auto bundleSysroot = root / "sysroot";
    for (const auto& directory : {sdk / "usr" / "include", sdk / "usr" / "lib", toolchain,
                                  bundleSysroot / "usr" / "include",
                                  bundleSysroot / "usr" / "lib"}) {
        std::filesystem::create_directories(directory, ec);
        if (ec)
            return Expected<std::filesystem::path>::failure("cannot create " + directory.string() +
                                                            ": " + ec.message());
    }

    auto saved = writeManifest(root, manifest);
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(sdk / "SDKSettings.plist", sdkSettingsPlist(manifest));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(root / platformName / "Info.plist", platformInfoPlist(manifest));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(root / toolchainName / "Info.plist", toolchainInfoPlist(manifest));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(root / "Linux.xcconfig", xcconfigContents(root));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeScript(root / "install.sh", installScriptContents());
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(root / "README.md", bundleReadme(manifest));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeFile(bundleSysroot / "README.md",
                      "Put Linux headers in usr/include and libraries in usr/lib.\n"
                      "No Apple SDK files belong here.\n");
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    saved = writeWrappers(root, manifest);
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    return std::filesystem::absolute(root).lexically_normal();
}

Validation validate(const std::filesystem::path& root) {
    Validation result;
    const auto manifestResult = readManifest(root);
    if (!manifestResult) {
        result.errors.push_back(manifestResult.error());
        return result;
    }
    const auto manifest = *manifestResult;
    const auto sdk = sdkPath(root);
    const auto bin = toolchainBin(root);

    const std::vector<std::filesystem::path> required = {
        root / manifestFileName,
        root / "README.md",
        root / "Linux.xcconfig",
        root / "install.sh",
        root / platformName / "Info.plist",
        root / toolchainName / "Info.plist",
        sdk / "SDKSettings.plist",
        bin / "clang",
        bin / "clang++",
        bin / "ar",
        bin / "nm",
        bin / "ranlib",
        bin / "ld",
        bin / "strip"};
    for (const auto& path : required)
        if (!fs::exists(path)) result.errors.push_back("missing file: " + path.string());

    for (const auto& path : {sdk / "SDKSettings.plist", root / platformName / "Info.plist",
                             root / toolchainName / "Info.plist"}) {
        auto text = fs::readText(path);
        if (!text) {
            result.errors.push_back("cannot read plist: " + path.string());
            continue;
        }
        plist::Document document;
        auto parsed = document.parse(*text);
        if (!parsed) result.errors.push_back("invalid plist " + path.string() + ": " + parsed.error());
    }

    plist::Document settings;
    auto settingsText = fs::readText(sdk / "SDKSettings.plist");
    if (settingsText) {
        auto parsed = settings.parse(*settingsText);
        if (parsed) {
            if (settings.valueAt("CanonicalName") != "linux")
                result.errors.push_back("SDKSettings.plist CanonicalName must be 'linux'");
            if (targetText(settings.root().find("isBaseSDK")) != "YES")
                result.errors.push_back("SDKSettings.plist isBaseSDK must be YES");
            if (settings.valueAt("DefaultProperties.PLATFORM_NAME") != "linux")
                result.errors.push_back("SDKSettings.plist PLATFORM_NAME must be 'linux'");
            if (settings.valueAt("CustomProperties.LINUX_SDK_BUNDLE").empty())
                result.errors.push_back("SDKSettings.plist is missing LINUX_SDK_BUNDLE");
        }
    }
    plist::Document toolchainInfo;
    auto toolchainText = fs::readText(root / toolchainName / "Info.plist");
    if (toolchainText && toolchainInfo.parse(*toolchainText))
        if (toolchainInfo.valueAt("Identifier") != manifest.identifier)
            result.errors.push_back("toolchain Identifier does not match the manifest");

    if (manifest.architectures.empty()) {
        result.errors.push_back("manifest lists no architectures");
    } else {
        std::set<std::string> seen;
        for (const auto& architecture : manifest.architectures) {
            if (llvmTarget(architecture).empty()) {
                result.errors.push_back("unsupported architecture: " + architecture);
                continue;
            }
            if (!seen.insert(architecture).second) {
                result.warnings.push_back("duplicate architecture: " + architecture);
                continue;
            }
            const auto compiler = bin / (architecture + "-unknown-linux-gnu-clang");
            const auto compilerCxx = bin / (architecture + "-unknown-linux-gnu-clang++");
            if (!isExecutable(compiler)) result.errors.push_back("not executable: " + compiler.string());
            if (!isExecutable(compilerCxx)) result.errors.push_back("not executable: " + compilerCxx.string());
        }
    }

    const auto sysroot = resolvedSysroot(root, manifest);
    if (!fs::exists(sysroot)) {
        result.errors.push_back("sysroot not found: " + sysroot.string());
    } else if (fs::exists(sysroot / "usr" / "include") && fs::exists(sysroot / "usr" / "lib")) {
        const bool hasHeaders = !std::filesystem::is_empty(sysroot / "usr" / "include");
        const bool hasLibraries = !std::filesystem::is_empty(sysroot / "usr" / "lib");
        if (!hasHeaders || !hasLibraries)
            result.warnings.push_back("sysroot is incomplete: populate usr/include and usr/lib");
    } else {
        result.warnings.push_back("sysroot should contain usr/include and usr/lib");
    }

    auto xcconfig = fs::readText(root / "Linux.xcconfig");
    if (xcconfig) {
        for (const auto* setting : {"SDKROOT", "CC", "CXX", "AR", "OTHER_LDFLAGS", "ARCHS"})
            if (xcconfig->find(std::string(setting) + " = ") == std::string::npos)
                result.errors.push_back(std::string("Linux.xcconfig is missing ") + setting);
    }
    if (manifest.clang.empty()) result.warnings.push_back("clang is resolved from PATH at build time");
    if (manifest.clangxx.empty()) result.warnings.push_back("clang++ is resolved from PATH at build time");
    if (manifest.llvmBin.empty()) result.warnings.push_back("LLVM tools are resolved from PATH at build time");
    return result;
}

Expected<std::filesystem::path> generateXcconfig(const std::filesystem::path& root,
                                                 const std::filesystem::path& outputPath) {
    if (!fs::exists(root / manifestFileName))
        return Expected<std::filesystem::path>::failure("not an LXcode Linux SDK bundle: " +
                                                        root.string());
    const auto destination = outputPath.empty() ? root / "Linux.xcconfig" : outputPath;
    auto saved = writeFile(destination, xcconfigContents(root));
    if (!saved) return Expected<std::filesystem::path>::failure(saved.error());
    return destination;
}

Expected<std::vector<std::filesystem::path>> install(const std::filesystem::path& root,
                                                     const std::filesystem::path& developerDir,
                                                     bool dryRun) {
    const auto check = validate(root);
    if (!check.ok())
        return Expected<std::vector<std::filesystem::path>>::failure(check.errors.front());
    if (developerDir.empty())
        return Expected<std::vector<std::filesystem::path>>::failure(
            "an Xcode developer directory is required");
    if (!dryRun && !fs::exists(developerDir))
        return Expected<std::vector<std::filesystem::path>>::failure("developer directory not found: " +
                                                                      developerDir.string());

    const auto platformTarget = developerDir / "Platforms" / platformName;
    const auto toolchainTarget = developerDir / "Toolchains" / toolchainName;
    if (dryRun) return std::vector<std::filesystem::path>{platformTarget, toolchainTarget};

    std::error_code ec;
    std::filesystem::create_directories(developerDir / "Platforms", ec);
    if (ec)
        return Expected<std::vector<std::filesystem::path>>::failure("cannot create Platforms: " +
                                                                      ec.message());
    std::filesystem::create_directories(developerDir / "Toolchains", ec);
    if (ec)
        return Expected<std::vector<std::filesystem::path>>::failure("cannot create Toolchains: " +
                                                                      ec.message());
    for (const auto& [source, destination] :
         {std::pair{root / platformName, platformTarget},
          std::pair{root / toolchainName, toolchainTarget}}) {
        std::filesystem::remove_all(destination, ec);
        if (ec)
            return Expected<std::vector<std::filesystem::path>>::failure(
                "cannot replace " + destination.string() + ": " + ec.message());
        std::filesystem::copy(source, destination, std::filesystem::copy_options::recursive, ec);
        if (ec)
            return Expected<std::vector<std::filesystem::path>>::failure(
                "cannot copy " + source.string() + ": " + ec.message());
    }
    return std::vector<std::filesystem::path>{platformTarget, toolchainTarget};
}

